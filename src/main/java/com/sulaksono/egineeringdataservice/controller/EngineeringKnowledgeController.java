package com.sulaksono.egineeringdataservice.controller;

import com.sulaksono.egineeringdataservice.config.AzureOpenAIProperties;
import com.sulaksono.egineeringdataservice.dto.CanonicalFileResult;
import com.sulaksono.egineeringdataservice.dto.EmbeddingGenerationRequest;
import com.sulaksono.egineeringdataservice.dto.EmbeddingGenerationResult;
import com.sulaksono.egineeringdataservice.dto.EmbeddingSearchResult;
import com.sulaksono.egineeringdataservice.dto.LiteralSearchRequest;
import com.sulaksono.egineeringdataservice.repository.CanonicalFileRepository;
import com.sulaksono.egineeringdataservice.service.EmbeddingService;
import com.sulaksono.egineeringdataservice.service.LiteralEmbeddingSearchService;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.CacheControl;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/api")
@RequiredArgsConstructor
@PreAuthorize("hasAnyRole('embedding-user','embedding-admin','assistant-admin')")
public class EngineeringKnowledgeController {

    private static final String EMBEDDING_PROVENANCE = "configured_embedding_model";
    private static final String EMBEDDING_DISCLOSURE =
            "This vector was generated by the configured embedding model, not by the chat model.";

    private final EmbeddingService embeddingService;
    private final AzureOpenAIProperties openAIProperties;
    private final LiteralEmbeddingSearchService literalSearchService;
    private final CanonicalFileRepository canonicalFileRepository;

    @PostMapping("/embeddings/generate")
    public ResponseEntity<EmbeddingGenerationResult> generate(
            @Valid @RequestBody EmbeddingGenerationRequest request) {
        float[] vector = embeddingService.generateEmbedding(request.text().trim());
        return noStore(new EmbeddingGenerationResult(
                "ok", EMBEDDING_PROVENANCE, openAIProperties.getEmbeddingModelDeployment(),
                vector.length, vector, EMBEDDING_DISCLOSURE));
    }

    @PostMapping("/embeddings/literal-search")
    public ResponseEntity<List<EmbeddingSearchResult>> literalSearch(
            @Valid @RequestBody LiteralSearchRequest request) {
        return noStore(literalSearchService.search(request));
    }

    @GetMapping("/canonical-files/{id}")
    public ResponseEntity<CanonicalFileResult> canonicalFile(@PathVariable UUID id) {
        return canonicalFileRepository.findById(id)
                .map(CanonicalFileResult::from)
                .map(EngineeringKnowledgeController::noStore)
                .orElseGet(() -> ResponseEntity.notFound()
                        .cacheControl(CacheControl.noStore()).build());
    }

    private static <T> ResponseEntity<T> noStore(T body) {
        return ResponseEntity.ok().cacheControl(CacheControl.noStore()).body(body);
    }
}
